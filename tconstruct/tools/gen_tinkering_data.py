#!/usr/bin/env python3
"""Writes the original's generated tinkering data (materials, stats, traits, modifiers, tool definitions and their tags) as one Rust source
file for the Tinkers API crate: the launcher stages only Rust and TOML files of the API folder, so the data goes in as string constants.

    python tconstruct/tools/gen_tinkering_data.py [SOURCE_TINKERING_DIR]

SOURCE defaults to .local/tconstruct-source/src/generated/resources/data/tconstruct/tinkering. The output is
tconstruct/mixins/tconstruct/api/src/tinkering_data.rs (checked in; rerun when the original's data is updated).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT = ROOT / '.local/tconstruct-source/src/generated/resources/data/tconstruct/tinkering'
OUT = ROOT / 'tconstruct/mixins/tconstruct/api/src/tinkering_data.rs'
SALVAGE = ROOT / '.local/tconstruct-source/src/generated/resources/data/tconstruct/recipes/tools/modifiers/salvage'
RECIPES = ROOT / '.local/tconstruct-source/src/generated/resources/data/tconstruct/recipes/tools/modifiers'
ITEM_TAGS = ROOT / 'tconstruct/content/data/tconstruct/tags/item'
FORGE_TAGS = ROOT / 'tconstruct/content/data/forge/tags/item'
KINDS = ('materials/definition', 'materials/stats', 'materials/traits', 'tags/materials', 'modifiers', 'tags/modifiers', 'tool_definitions')


def main(argv):
    source = Path(argv[1]) if len(argv) > 1 else DEFAULT
    lines = [
        '//! Generated by tconstruct/tools/gen_tinkering_data.py from the original\'s generated data. Do not edit.',
        '//! Each entry is (kind, id, JSON): the kind is the folder under `tinkering`, the id `namespace:name` of the file.',
        'pub static FILES: &[(&str, &str, &str)] = &[',
    ]
    count = 0
    for kind in KINDS:
        base = source / kind
        for path in sorted(base.rglob('*.json')):
            name = path.relative_to(base).with_suffix('').as_posix()
            data = json.dumps(json.loads(path.read_bytes().decode('utf-8')), separators=(',', ':'), ensure_ascii=False)
            lines.append(f'    ("{kind}", "tconstruct:{name}", r####"{data}"####),')
            count += 1
    # what a modifier costs in slots and the tools it goes on: the modifier salvage recipes (the recipe types that add a modifier name them too)
    for path in sorted(SALVAGE.rglob('*.json')):
        data = json.loads(path.read_bytes().decode('utf-8'))
        if data.get('type') != 'tconstruct:modifier_salvage' or 'compat' in path.parts:
            continue
        name = path.relative_to(SALVAGE).with_suffix('').as_posix()
        lines.append(f'    ("modifier_salvage", "tconstruct:{name}", r####"{json.dumps(data, separators=(",", ":"), ensure_ascii=False)}"####),')
        count += 1
    # what a modifier costs in items: the recipes that add one level (single, incremental and the two multilevel kinds; swappable and overslime are not used)
    for folder in ('upgrade', 'ability', 'defense'):
        for path in sorted((RECIPES / folder).glob('*.json')):
            data = json.loads(path.read_bytes().decode('utf-8'))
            if data.get('type') not in ('tconstruct:modifier', 'tconstruct:incremental_modifier', 'tconstruct:multilevel_modifier', 'tconstruct:multilevel_incremental_modifier'):
                continue
            keep = data
            lines.append(f'    ("modifier_recipes", "tconstruct:{folder}/{path.stem}", r####"{json.dumps(keep, separators=(",", ":"), ensure_ascii=False)}"####),')
            count += 1
    # the item tags the recipes name (forge:), with the tags they nest, so a station can tell what an ingredient accepts
    wanted, seen = set(), set()
    for line in lines:
        wanted.update(t for t in __import__('re').findall(r'"tag":"(forge:[^"]+)"', line) if line.startswith('    ("modifier_recipes"'))
    while wanted:
        tag = wanted.pop()
        seen.add(tag)
        path = FORGE_TAGS / (tag.split(':', 1)[1] + '.json')
        if not path.exists():
            continue
        data = json.dumps(json.loads(path.read_bytes().decode('utf-8')), separators=(',', ':'), ensure_ascii=False)
        lines.append(f'    ("tags/forge_item", "{tag}", r####"{data}"####),')
        count += 1
        wanted.update(t[1:] for t in __import__('re').findall(r'"(#forge:[^"]+)"', data) if t[1:] not in seen)
    # the item tags the tool stats and modifiers name (the content owns them)
    for path in sorted((ITEM_TAGS / 'modifiable').rglob('*.json')) + [ITEM_TAGS / 'modifiable.json']:
        name = path.relative_to(ITEM_TAGS).with_suffix('').as_posix()
        data = json.dumps(json.loads(path.read_bytes().decode('utf-8')), separators=(',', ':'), ensure_ascii=False)
        lines.append(f'    ("tags/item", "tconstruct:{name}", r####"{data}"####),')
        count += 1
    lines.append('];')
    enchantments = source / 'enchantments_to_modifiers.json'
    data = json.dumps(json.loads(enchantments.read_bytes().decode('utf-8')), separators=(',', ':'), ensure_ascii=False)
    lines.append(f'pub static ENCHANTMENTS_TO_MODIFIERS: &str = r####"{data}"####;')
    OUT.write_bytes(('\n'.join(lines) + '\n').encode('utf-8'))
    print(f'{count} files, {OUT.stat().st_size} bytes')


if __name__ == '__main__':
    main(sys.argv)
