#!/usr/bin/env python3
"""Writes the original's generated tinkering data (materials, stats, traits, modifiers, tool definitions and their tags) as one Rust source
file for the Tinkers API crate: the launcher stages only Rust and TOML files of the API folder, so the data goes in as string constants.

    python tconstruct/tools/gen_tinkering_data.py [SOURCE_TINKERING_DIR]

SOURCE defaults to .local/tconstruct-source/src/generated/resources/data/tconstruct/tinkering. The output is
tconstruct/mixins/tconstruct/api/src/tinkering_data.rs (checked in; rerun when the original's data is updated).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT = ROOT / '.local/tconstruct-source/src/generated/resources/data/tconstruct/tinkering'
OUT = ROOT / 'tconstruct/mixins/tconstruct/api/src/tinkering_data.rs'
KINDS = ('materials/definition', 'materials/stats', 'materials/traits', 'tags/materials', 'modifiers', 'tags/modifiers', 'tool_definitions')


def main(argv):
    source = Path(argv[1]) if len(argv) > 1 else DEFAULT
    lines = [
        '//! Generated by tconstruct/tools/gen_tinkering_data.py from the original\'s generated data. Do not edit.',
        '//! Each entry is (kind, id, JSON): the kind is the folder under `tinkering`, the id `namespace:name` of the file.',
        'pub static FILES: &[(&str, &str, &str)] = &[',
    ]
    count = 0
    for kind in KINDS:
        base = source / kind
        for path in sorted(base.rglob('*.json')):
            name = path.relative_to(base).with_suffix('').as_posix()
            data = json.dumps(json.loads(path.read_bytes().decode('utf-8')), separators=(',', ':'), ensure_ascii=False)
            lines.append(f'    ("{kind}", "tconstruct:{name}", r####"{data}"####),')
            count += 1
    lines.append('];')
    enchantments = source / 'enchantments_to_modifiers.json'
    data = json.dumps(json.loads(enchantments.read_bytes().decode('utf-8')), separators=(',', ':'), ensure_ascii=False)
    lines.append(f'pub static ENCHANTMENTS_TO_MODIFIERS: &str = r####"{data}"####;')
    OUT.write_bytes(('\n'.join(lines) + '\n').encode('utf-8'))
    print(f'{count} files, {OUT.stat().st_size} bytes')


if __name__ == '__main__':
    main(sys.argv)
