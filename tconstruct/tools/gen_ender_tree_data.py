#!/usr/bin/env python3
"""Embed the original configured Ender trees in the standalone native API bundle.

The source-reference JSON remains authoritative. Native bundles already accept
Rust sources; embedding avoids runtime reads outside the installed mod and does
not change the original codec data or relax the bundle's file allowlist.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REFERENCE = ROOT / 'tconstruct/content/reference/slime-islands/data/tconstruct/worldgen/configured_feature'
OUTPUT = ROOT / 'tconstruct/mixins/tconstruct/api/src/source_tree_data.rs'


def main():
    lines = ['// Generated by tconstruct/tools/gen_ender_tree_data.py from original source-reference JSON.',
             '// Used by real sapling growth; do not substitute normalized legacy tree constants.']
    for constant, name in [('SMALL', 'ender_slime_tree.json'), ('TALL', 'ender_slime_tree_tall.json')]:
        value = json.loads((REFERENCE / name).read_text(encoding='utf-8'))
        if value.get('type') != 'minecraft:tree':
            raise ValueError(f'not an original tree configuration: {name}')
        text = json.dumps(value, separators=(',', ':'), ensure_ascii=False)
        if '"####' in text:
            raise ValueError('Rust raw-string delimiter in tree data')
        lines.append(f'pub const {constant}: &str = r####"{text}"####;')
    OUTPUT.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'Embedded two original Ender configurations: {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
