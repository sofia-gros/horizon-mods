"""Pinned Seared machinery recipe unlocks mapped to existing native recipes."""
import json
import sys
import tempfile
import unittest
import zipfile
from pathlib import Path

MOD = Path(__file__).resolve().parents[1]
DATA = MOD / 'content/data/tconstruct'
GROUPS = {
    'decorations': ('melter', 'heater', 'basin', 'table'),
    'redstone': ('faucet', 'fuel_tank', 'fuel_gauge', 'ingot_tank', 'ingot_gauge', 'drain', 'chute'),
}
sys.path.insert(0, str(MOD / 'tools'))
from package_hmod import package


def advancement_path(group, name):
    return f'advancement/recipes/{group}/survival_seared_{name}.json'


class SearedRecipeUnlocks(unittest.TestCase):
    def test_exact_source_conditions_and_native_recipe_rewards(self):
        for group, names in GROUPS.items():
            for name in names:
                with self.subTest(name=name):
                    recipe_id = f'tconstruct:survival_seared_{name}'
                    value = json.loads((DATA / advancement_path(group, name)).read_text())
                    self.assertEqual(value, {
                        'parent': 'minecraft:recipes/root',
                        'criteria': {
                            'has_item': {
                                'trigger': 'minecraft:inventory_changed',
                                'conditions': {'items': [{'items': ['tconstruct:seared_brick']}]},
                            },
                            'has_the_recipe': {
                                'trigger': 'minecraft:recipe_unlocked',
                                'conditions': {'recipes': recipe_id},
                            },
                        },
                        'requirements': [['has_item', 'has_the_recipe']],
                        'rewards': {'recipes': [recipe_id]},
                        'sends_telemetry_event': False,
                    })
                    recipe = json.loads((DATA / f'recipe/survival_seared_{name}.json').read_text())
                    self.assertEqual(recipe['type'], 'minecraft:crafting_shaped')
                    self.assertEqual(recipe['result']['id'], f'tconstruct:seared_{name}')

    def test_native_recipes_still_match_source_shapes_outputs_and_counts(self):
        with zipfile.ZipFile(MOD / 'content/reference/tconstruct-recipes.zip') as archive:
            for names in GROUPS.values():
                for name in names:
                    with self.subTest(name=name):
                        source = json.loads(archive.read(f'data/tconstruct/recipes/smeltery/seared/{name}.json'))
                        native = json.loads((DATA / f'recipe/survival_seared_{name}.json').read_text())
                        self.assertEqual(native['pattern'], source['pattern'])
                        self.assertEqual(native['result']['id'], source['result']['item'])
                        self.assertEqual(native['result'].get('count', 1), source['result'].get('count', 1))

    def test_package_includes_unlocks_recipes_and_registered_items(self):
        with tempfile.TemporaryDirectory() as tmp:
            output = Path(tmp) / 'tconstruct.hmod'
            package(output)
            with zipfile.ZipFile(output) as archive:
                # Seared Brick is generated by package_hmod from resources.py.
                self.assertIsInstance(json.loads(archive.read('data/tconstruct/horizon/item/seared_brick.json')), dict)
                for group, names in GROUPS.items():
                    for name in names:
                        with self.subTest(name=name):
                            for path in (advancement_path(group, name), f'recipe/survival_seared_{name}.json'):
                                self.assertEqual(json.loads(archive.read('data/tconstruct/' + path)),
                                                 json.loads((DATA / path).read_text()))
                            block = json.loads(archive.read(f'data/tconstruct/horizon/block/seared_{name}.json'))
                            self.assertTrue(block.get('item', True))


if __name__ == '__main__':
    unittest.main()
