// Bounded translation of the pinned Mantle piglin-barter loot injection.
// The source also has two unsupported material-dependent entries (weights 5/8).
use serde_json::{Value, json};

// SHA-256 of the complete normalized vanilla 26.3 table, including its sole
// pool, entry modifiers, and random_sequence. A pool named "main" alone is not
// proof: other pools or modifiers can indirectly produce the same lantern.
const VANILLA_TABLE_SHA256: &str =
    "dc78edd79b366026dcbd1410e2244d7a76de4558d67efd4c0cf634ebd7d76733";

fn vanilla_table(table: &Value) -> bool {
    use sha2::{Digest, Sha256};
    serde_json::to_vec(table)
        .ok()
        .is_some_and(|bytes| format!("{:x}", Sha256::digest(bytes)) == VANILLA_TABLE_SHA256)
}

pub(super) fn inject(id: &str, table: &mut Value) -> bool {
    if id != "minecraft:gameplay/piglin_bartering" || !vanilla_table(table) {
        return false;
    }
    let Some(entries) = table["pools"][0]["entries"].as_array_mut() else {
        return false;
    };
    entries.push(json!({
        "type":"minecraft:item", "name":"tconstruct:scorched_lantern", "weight":20,
        "modifier":[
            {"type":"tconstruct:blazing_barter_lantern"},
            {"type":"minecraft:set_count","count":{"type":"minecraft:uniform","min":1,"max":4}}
        ]
    }));
    true
}

// Items::loot_table executes this native function, then its ordinary set_count.
// Only the fresh, unmodified lantern generated by this entry is handled.
pub(super) fn fill(kind: &str, data: &Value, stack: &mut super::LootStack) -> bool {
    if kind != "tconstruct:blazing_barter_lantern"
        || stack.item != "tconstruct:scorched_lantern"
        || data.as_object().is_none_or(|obj| {
            obj.len() != 1 || obj.get("type").and_then(Value::as_str) != Some(kind)
        })
        || stack
            .components
            .iter()
            .any(|(id, _)| id == "minecraft:custom_data")
    {
        return false;
    }
    stack.components.push((
        "minecraft:custom_data".into(),
        json!({"tconstruct:tank":{"fluid":"tconstruct:blazing_blood","amount":50}}),
    ));
    true
}

// Tests use the player's prepared resource, never redistribute Minecraft data.
#[cfg(test)]
pub(super) fn testing_stock_table() -> Value {
    let path = std::env::var_os("TCONSTRUCT_TEST_PIGLIN_BARTER_TABLE")
        .expect("set TCONSTRUCT_TEST_PIGLIN_BARTER_TABLE to the prepared vanilla 26.3 table");
    let table = serde_json::from_slice(&std::fs::read(path).expect("read vanilla barter fixture"))
        .expect("parse vanilla barter fixture");
    assert!(
        vanilla_table(&table),
        "expected the pinned vanilla 26.3 table"
    );
    table
}

#[cfg(test)]
mod tests {
    use super::*;
    fn table() -> Value {
        testing_stock_table()
    }
    #[test]
    fn appends_once_to_existing_weighted_pool_only() {
        let mut t = table();
        let before = t.clone();
        assert!(inject("minecraft:gameplay/piglin_bartering", &mut t));
        let entries = t["pools"][0]["entries"].as_array().unwrap();
        assert_eq!(
            &entries[..entries.len() - 1],
            before["pools"][0]["entries"].as_array().unwrap().as_slice()
        );
        assert_eq!(entries.last().unwrap()["weight"], 20);
        assert_eq!(entries.len(), 20);
        assert_eq!(
            entries
                .iter()
                .map(|e| e["weight"].as_u64().unwrap_or(1))
                .sum::<u64>(),
            489
        );
        assert_eq!(t["pools"].as_array().unwrap().len(), 1);
        let once = t.clone();
        assert!(!inject("minecraft:gameplay/piglin_bartering", &mut t));
        assert_eq!(t, once);
    }
    #[test]
    fn native_function_sets_only_fresh_expected_lantern() {
        let mut stack = super::super::LootStack {
            item: "tconstruct:scorched_lantern".into(),
            count: 1,
            damage: 0,
            enchantments: vec![],
            potion: None,
            map: false,
            exploration: None,
            ominous_amplifier: None,
            stew_effects: vec![],
            names: vec![],
            components: vec![],
        };
        let data = json!({"type":"tconstruct:blazing_barter_lantern"});
        assert!(fill("tconstruct:blazing_barter_lantern", &data, &mut stack));
        assert_eq!(stack.components[0].1["tconstruct:tank"]["amount"], 50);
        assert_eq!(
            stack.components[0].1["tconstruct:tank"]["fluid"],
            "tconstruct:blazing_blood"
        );
        let prior = stack.clone();
        assert!(!fill(
            "tconstruct:blazing_barter_lantern",
            &data,
            &mut stack
        ));
        assert_eq!(stack, prior);
        stack.item = "minecraft:stone".into();
        stack.components.clear();
        assert!(!fill(
            "tconstruct:blazing_barter_lantern",
            &data,
            &mut stack
        ));
    }
    #[test]
    fn refuse_modified_tables_and_existing_nested_entries() {
        for change in 0..13 {
            let mut t = table();
            match change {
                0 => t["modifier"] = json!([{"type":"example:custom"}]),
                1 => t["pools"][0]["modifier"] = json!([{"type":"example:custom"}]),
                2 => t["pools"][0]["rolls"] = json!(2),
                3 => {
                    let pool = t["pools"][0].clone();
                    t["pools"].as_array_mut().unwrap().push(pool);
                }
                4 => {
                    t["pools"][0]["entries"][0] =
                        json!({"type":"minecraft:loot_table","value":"example:unknown"});
                }
                5 => {
                    t["pools"][0]["entries"][0] = json!({"type":"minecraft:alternatives","children":[{"type":"minecraft:item","name":"tconstruct:scorched_lantern"}]})
                }
                6 => {
                    t["pools"][0]["name"] = json!("main");
                    t["pools"].as_array_mut().unwrap().push(json!({"rolls":1,"entries":[{"type":"minecraft:loot_table","value":"example:unknown"}]}));
                }
                7 => {
                    t["pools"][0]["entries"][0]["modifier"] =
                        json!({"type":"minecraft:reference","name":"example:unknown"})
                }
                8 => t["random_sequence"] = json!("example:changed"),
                9 => t["type"] = json!("minecraft:generic"),
                10 => t["condition"] = json!({"type":"example:unknown"}),
                11 => t["pools"][0]["entries"][0]["weight"] = json!(999),
                _ => t["pools"][0]["name"] = json!("main"),
            }
            let before = t.clone();
            assert!(!inject("minecraft:gameplay/piglin_bartering", &mut t));
            assert_eq!(t, before);
        }
    }
    #[test]
    fn ambiguous_or_unrelated_pools_are_untouched() {
        let mut t = table();
        t["pools"][0]["name"] = json!("main");
        t["pools"][0]["entries"] =
            json!([{"type":"minecraft:item","name":"minecraft:stone","weight":3}]);
        let before = t.clone();
        assert!(!inject("minecraft:gameplay/piglin_bartering", &mut t));
        assert_eq!(t, before);
        let mut t = table();
        let before = t.clone();
        assert!(!inject("minecraft:chests/test", &mut t));
        assert_eq!(t, before);
        let mut t = table();
        t["pools"][0]["bonus_rolls"] = json!(1);
        let before = t.clone();
        assert!(!inject("minecraft:gameplay/piglin_bartering", &mut t));
        assert_eq!(t, before);
        let mut t = table();
        t["pools"][0]["condition"] = json!({"type":"example:unknown"});
        let before = t.clone();
        assert!(!inject("minecraft:gameplay/piglin_bartering", &mut t));
        assert_eq!(t, before);
    }
}
