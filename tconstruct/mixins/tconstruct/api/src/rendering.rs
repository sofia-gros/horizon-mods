    #[test]
    fn liquid_heights_share_the_capacity_keep_a_minimum_and_take_the_excess_from_the_tallest() {
        // full: the shares are exact, nothing is held back for the empty part
        assert_eq!(calc_liquid_heights(&[600, 400], 1000, 1990, 100), [1194, 796]);
        // nearly empty: every fluid keeps the minimum, then the excess comes off the tallest in turn
        assert_eq!(calc_liquid_heights(&[10, 10, 10], 3000, 190, 100), [30, 30, 30]);
        // one fluid, half full of a two block tank: half the height less the empty reserve
        assert_eq!(calc_liquid_heights(&[500], 1000, 1990, 100), [995]);
        assert!(calc_liquid_heights(&[], 1000, 1990, 100).is_empty());
        assert_eq!(calc_liquid_heights(&[500], 0, 1990, 100), [0]);
    }

    #[test]
    fn a_scaled_cuboid_fills_from_the_bottom_or_hangs_from_the_top_for_a_gas() {
        let cuboid = Cuboid { from: [0.08, 8.08, 0.08], to: [15.92, 15.92, 15.92], faces: &[] };
        let half = scaled(&cuboid, 0.5, true, false);
        assert!((half.from[1] - 8.08).abs() < 1e-6 && (half.to[1] - 12.0).abs() < 1e-6);
        let gas = scaled(&cuboid, 0.5, true, true);
        assert!((gas.from[1] - 12.0).abs() < 1e-6 && (gas.to[1] - 15.92).abs() < 1e-6);
        // without the flip a gas fills from the bottom like anything else
        let unflipped = scaled(&cuboid, 0.5, false, true);
        assert!((unflipped.to[1] - 12.0).abs() < 1e-6);
        // overfull clamps to the whole cuboid
        assert!((scaled(&cuboid, 2.0, true, false).to[1] - 15.92).abs() < 1e-6);
    }

