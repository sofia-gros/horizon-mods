        structure.insert("max".into(), Nbt::Compound(max));
        let fluids: Vec<Nbt> = [("tconstruct:molten_iron", 500), ("tconstruct:molten_gold", 250)].iter().map(|(name, amount)| {
            let mut entry = NbtCompound::new();
            entry.insert("FluidName".into(), Nbt::String(name.to_string()));
            entry.insert("Amount".into(), Nbt::Int(*amount));
            Nbt::Compound(entry)
        }).collect();
        let mut tank = NbtCompound::new();
        tank.insert("fluids".into(), Nbt::List(fluids));
        tank.insert("capacity".into(), Nbt::Int(3000));
        let mut inventory = NbtCompound::new();
        inventory.insert("size".into(), Nbt::Int(5));
        let mut data = NbtCompound::new();
        data.insert("multiblock".into(), Nbt::Compound(structure));
        data.insert("tank".into(), Nbt::Compound(tank));
        data.insert("inventory".into(), Nbt::Compound(inventory));
        let items = [Some(stack("minecraft:iron_ingot")), None, Some(stack("minecraft:gold_ingot"))];
        let log = run("tconstruct:smeltery_controller", &data, &items, vec![("in_structure", "true"), ("facing", "south")]);
        // the inside is one in from the walls: min (-1,-1,-2) to max (2,1,1) gives the inside corner (0,0,-1), 2 by 2 by 2
        assert!(log.iter().any(|line| line == "translate [0.0000, 0.0000, -1.0000]"), "{log:?}");
        // heights 332 and 166 of 1990 units: iron to 0.337, gold on top of it to 0.503
        assert!(log.iter().any(|line| line == "cube tconstruct:fluid/molten/ore/iron/still [0.0050, 0.0050, 0.0050] -> [1.9950, 0.3370, 1.9950] tint FFFFFF"), "{log:?}");
        assert!(log.iter().any(|line| line == "cube tconstruct:fluid/molten/ore/gold/still [0.0050, 0.3370, 0.0050] -> [1.9950, 0.5030, 1.9950] tint FFFFFF"), "{log:?}");
        // slot 0 at the first cell, slot 2 two cells on (a layer is 2 by 2), both at 15/16 size turned to the facing
        assert!(log.iter().any(|line| line == "translate [0.5000, 0.5000, 0.5000]"), "{log:?}");
        assert!(log.iter().any(|line| line == "translate [0.5000, 0.5000, 1.5000]"), "{log:?}");
