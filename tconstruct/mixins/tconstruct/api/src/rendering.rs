//! The block entity renderers, from SlimeKnights' client renderers and Mantle's FluidRenderer, RenderingHelper and
//! ChannelFluids (MIT; see LICENSE): the melter (TankInventoryBlockEntityRenderer), the seared and scorched tanks
//! (TankBlockEntityRenderer), the casting table and basin (CastingBlockEntityRenderer), the faucet
//! (FaucetBlockEntityRenderer), the channel (ChannelBlockEntityRenderer) and the smeltery and foundry controllers
//! (HeatingStructureBlockEntityRenderer with SmelteryTankRenderer). The cuboids and item placements they draw are the
//! original's model data (`crate::render_data`, generated by tools/import_original_data.py from Mantle's
//! `mantle/model` data); a fluid's still and flowing textures and tint are its Mantle fluid texture data and its
//! `FluidDef` (the tint and the gas test — a fluid lighter than air has a negative density and hangs from the top of
//! its cuboid when the renderer flips gas, as `renderFluidTank` is called with flipGas for the melter and the tanks).
//!
//! What the host cannot express yet, named rather than faked:
//! - The canvas tint is `0xRRGGBB` — there is no alpha. The casting renderer's fades (the fluid's opacity in the last
//!   10% of cooling, the recipe output item fading in through `CastingItemRenderTypeBuffer`) are drawn solid instead.
//! - The canvas has no light parameter, so `FluidRenderer.withBlockLight` (raising the quad light to the fluid's
//!   light level) cannot be applied; the host lights the geometry, and the blocks' own `light` state already
//!   follows the fluid for the tanks.
//! - A renderer sees only its own block entity: no neighbouring blocks. The faucet's stream below it is drawn
//!   anyway: its client tick walks the blocks below through the client world view and keeps their states in transient
//!   client data (`stream`), and the renderer draws each block's own `faucet_fluid` cuboids translated down (Mantle's
//!   `RenderingHelper.renderFaucetFluids`). The channel's down stream is not drawn yet — it needs the same client tick
//!   of its own — and the channel's edge cuboid — drawn by the original only against a neighbour that is not the same
//!   channel — is drawn unconditionally.
//! - The display contexts of `TinkerItemDisplays` (melter, casting table, casting basin) are custom; the canvas
//!   knows only the vanilla contexts, so an item is drawn with the original context's fallback (fixed for the
//!   casting table, none for the melter and the basin), at the position, rotation and size of its RenderItem data.
//! - `FluidTankAnimated`'s render offset (the easing of the drawn height when the amount changes) is client tank
//!   state the host does not keep; heights are drawn at the amount itself.
//! - The smeltery's error-block highlight is not drawn: the original draws it as a translucent shape (red for
//!   ten seconds after an error update, or an outline while the player holds the book for the debug view), and
//!   the canvas has neither alpha nor a line or outline primitive — every quad it draws carries a sprite. The
//!   error position itself is already in the controller's synced data (`lastError`), so a canvas that gains
//!   such a primitive can draw it without new data plumbing. The matching message on use is likewise
//!   undelivered: no block entity use or menu context here carries a player to send it to.
use crate::render_data::{self, Cuboid, Face};
use pluto_lib::{
    BlockEntityCanvas, BlockEntityRender, BlockEntityRendererRegistry, BlockState, Direction, FluidRegistry, FluidStack, Identifier, ItemDisplayContext, ItemSlot,
    NbtCompound, NbtCompoundExt,
};

/// A fluid's drawn appearance: the still and flowing sprites, the tint (`0xRRGGBB`) and whether it is a gas
/// (lighter than air: a negative density, as `FluidType.isLighterThanAir`).
#[derive(Clone, Debug, PartialEq)]
pub(crate) struct Visual { pub still: String, pub flowing: String, pub tint: u32, pub gas: bool }

/// The appearance of a fluid: its textures from the original's fluid texture data (vanilla's two fluids, whose
/// textures every tank may hold, are named directly), its tint and gas test from its fluid definition.
pub(crate) fn visual(fluid: &Identifier) -> Option<Visual> {
    let id = fluid.to_string();
    let (still, flowing) = match render_data::fluid_texture(&id) {
        Some(texture) => (texture.still.to_owned(), texture.flowing.to_owned()),
        None => match id.as_str() {
            "minecraft:lava" => ("minecraft:block/lava_still".to_owned(), "minecraft:block/lava_flow".to_owned()),
            "minecraft:water" => ("minecraft:block/water_still".to_owned(), "minecraft:block/water_flow".to_owned()),
            _ => return None,
        },
    };
    let def = FluidRegistry::get(&id);
    let gas = def.as_ref().is_some_and(|def| def.attributes.density < 0);
    let tint = def.map_or(if id == "minecraft:water" { 0x3F76E4 } else { 0xFFFFFF }, |def| def.attributes.color & 0x00FF_FFFF);
    Some(Visual { still, flowing, tint, gas })
}

/// The fluid in host tank `index` of a block entity's saved data (the host's own tank storage, `fluids`).
pub(crate) fn host_tank(data: &NbtCompound, index: usize) -> Option<FluidStack> {
    let tank = data.get("fluids")?.as_list()?.get(index)?.as_compound()?;
    let name = tank.get("Fluid")?.as_str()?;
    let amount = tank.get("Amount")?.as_i64()?;
    if name == "minecraft:empty" || amount <= 0 { return None; }
    // the tag is optional in the saved tank format, absent in data written before stacks carried one
    let tag = tank.get("Tag").and_then(|tag| tag.as_compound().cloned());
    Some(FluidStack { fluid: Identifier::parse(name).ok()?, amount: amount as u32, tag })
}

/// The block state variant of `variants` the canvas's state asks for: the specific variant whose properties all
/// match, else the default (the variant that asks for nothing). A specific variant must win: the default asks for
/// nothing, so it matches every state and would hide every specific variant behind it (the faucet's `facing=down`
/// column, the fluid cannons' down and up placements).
pub(crate) fn variant_data<'a, T>(variants: &'a [render_data::Variant<T>], canvas: &dyn BlockEntityCanvas) -> &'a [T] {
    variants.iter()
        .find(|variant| !variant.when.is_empty() && variant.when.iter().all(|(name, wanted)| canvas.state_property(name).as_deref() == Some(*wanted)))
        .or_else(|| variants.iter().find(|variant| variant.when.is_empty()))
        .map_or(&[], |variant| variant.data)
}

/// The rotation of a block model from its canonical north facing to `facing`, in degrees (the block state's own
/// `y` values: east 90, south 180, west 270). Mantle's `RenderingHelper.applyRotation` turns the model data, which
/// is authored facing north, by the same amount.
pub(crate) fn facing_degrees(facing: &str) -> f32 {
    match facing { "east" => 90.0, "south" => 180.0, "west" => 270.0, _ => 0.0 }
}

fn rotate_to_facing(canvas: &mut dyn BlockEntityCanvas, facing: &str) {
    let degrees = facing_degrees(facing);
    if degrees != 0.0 { canvas.rotate_about([0.0, 1.0, 0.0], degrees, [0.5, 0.0, 0.5]); }
}

/// The rotation that turns a south-facing model (the channel's side cuboids) to `side`.
fn rotate_to_side(canvas: &mut dyn BlockEntityCanvas, side: Direction) {
    let degrees = (facing_degrees(side.name()) + 180.0) % 360.0;
    if degrees != 0.0 { canvas.rotate_about([0.0, 1.0, 0.0], degrees, [0.5, 0.0, 0.5]); }
}

/// `renderScaledCuboid`'s box: the cuboid filled to `scale` of its height from the bottom, or from the top for a
/// gas when the renderer flips gas (`flipGas`).
pub(crate) fn scaled(cuboid: &Cuboid, scale: f32, flip_gas: bool, gas: bool) -> Cuboid {
    let scale = scale.clamp(0.0, 1.0);
    let mut out = Cuboid { from: cuboid.from, to: cuboid.to, faces: cuboid.faces };
    let height = cuboid.to[1] - cuboid.from[1];
    if flip_gas && gas { out.from[1] = cuboid.to[1] - height * scale; } else { out.to[1] = cuboid.from[1] + height * scale; }
    out
}

/// The four corners of one face of the box from `from` to `to` (in blocks), wound counter-clockwise seen from
/// outside the box, and the face's texture region in texels: `u` and `v` run along the face's plane, `v` downward
/// on the sides as a texture's does. A face whose `u` runs against its plane's axis measures `u` back from the far
/// edge, so the corners stay in (u0, v0), (u0, v1), (u1, v1), (u1, v0) order.
fn face_quad(dir: &str, from: [f32; 3], to: [f32; 3]) -> ([[f32; 3]; 4], [f32; 4]) {
    let (x0, y0, z0) = (from[0], from[1], from[2]);
    let (x1, y1, z1) = (to[0], to[1], to[2]);
    match dir {
        "up" => ([[x0, y1, z0], [x0, y1, z1], [x1, y1, z1], [x1, y1, z0]], [x0 * 16.0, z0 * 16.0, x1 * 16.0, z1 * 16.0]),
        "down" => ([[x1, y0, z0], [x1, y0, z1], [x0, y0, z1], [x0, y0, z0]], [(1.0 - x1) * 16.0, z0 * 16.0, (1.0 - x0) * 16.0, z1 * 16.0]),
        "north" => ([[x1, y1, z0], [x1, y0, z0], [x0, y0, z0], [x0, y1, z0]], [(1.0 - x1) * 16.0, (1.0 - y1) * 16.0, (1.0 - x0) * 16.0, (1.0 - y0) * 16.0]),
        "south" => ([[x0, y1, z1], [x0, y0, z1], [x1, y0, z1], [x1, y1, z1]], [x0 * 16.0, (1.0 - y1) * 16.0, x1 * 16.0, (1.0 - y0) * 16.0]),
        "west" => ([[x0, y1, z0], [x0, y0, z0], [x0, y0, z1], [x0, y1, z1]], [z0 * 16.0, (1.0 - y1) * 16.0, z1 * 16.0, (1.0 - y0) * 16.0]),
        _ => ([[x1, y1, z1], [x1, y0, z1], [x1, y0, z0], [x1, y1, z0]], [(1.0 - z1) * 16.0, (1.0 - y1) * 16.0, (1.0 - z0) * 16.0, (1.0 - y0) * 16.0]),
    }
}

fn draw_face(canvas: &mut dyn BlockEntityCanvas, face: &Face, from: [f32; 3], to: [f32; 3], visual: &Visual) {
    let (mut corners, uv) = face_quad(face.dir, from, to);
    // a rotated face turns its texture: the corners move on by the rotation (exact for the 180° the data uses)
    corners.rotate_left((face.rotation / 90) as usize % 4);
    let sprite = if face.flowing { &visual.flowing } else { &visual.still };
    canvas.quad(sprite, corners, uv, visual.tint);
}

/// Draws a fluid cuboid (Mantle's `renderCuboid`): a box with every face and no flowing face is the canvas's own
/// cube; anything else is drawn face by face, each face with its own sprite.
pub(crate) fn draw_cuboid(canvas: &mut dyn BlockEntityCanvas, cuboid: &Cuboid, visual: &Visual) {
    let from = [cuboid.from[0] / 16.0, cuboid.from[1] / 16.0, cuboid.from[2] / 16.0];
    let to = [cuboid.to[0] / 16.0, cuboid.to[1] / 16.0, cuboid.to[2] / 16.0];
    if cuboid.faces.len() == 6 && cuboid.faces.iter().all(|face| !face.flowing && face.rotation == 0) {
        canvas.cube(from, to, &visual.still, visual.tint);
        return;
    }
    for face in cuboid.faces { draw_face(canvas, face, from, to, visual); }
}

/// The display context a RenderItem's transform falls back to without Tinkers' custom contexts: the casting
/// table's is fixed, the melter's and the casting basin's are none (`TinkerItemDisplays`).
fn display_context(transform: &str) -> ItemDisplayContext {
    match transform { "tconstruct:casting_table" => ItemDisplayContext::Fixed, _ => ItemDisplayContext::None }
}

/// `RenderingHelper.renderItem`: the stack at the placement's center, turned by its x and y rotation, scaled to
/// its size, drawn with its display context.
pub(crate) fn draw_item(canvas: &mut dyn BlockEntityCanvas, stack: &ItemSlot, place: &render_data::RenderItem) {
    canvas.push();
    canvas.translate([place.center[0] / 16.0, place.center[1] / 16.0, place.center[2] / 16.0]);
    if place.x != 0.0 { canvas.rotate_about([1.0, 0.0, 0.0], place.x, [0.0; 3]); }
    if place.y != 0.0 { canvas.rotate_about([0.0, 1.0, 0.0], place.y, [0.0; 3]); }
    let size = place.size / 16.0;
    canvas.scale([size, size, size]);
    canvas.item_with_context(stack, display_context(place.transform));
    canvas.pop();
}

/// TankInventoryBlockEntityRenderer: the melter's fluid in its half tank and the items being melted, the whole
/// turned to the block's facing. The tank is host tank 0; its capacity is the melter's.
fn render_melter(render: &mut BlockEntityRender<'_>) {
    let canvas = &mut *render.canvas;
    let facing = canvas.state_property("facing").unwrap_or_else(|| "north".to_owned());
    canvas.push();
    rotate_to_facing(canvas, &facing);
    if let Some(fluid) = host_tank(render.data, 0) {
        if let (Some(cuboids), Some(visual)) = (render_data::fluid_cuboids(render.block), visual(&fluid.fluid)) {
            let scale = fluid.amount as f32 / crate::heating::MELTER_CAPACITY as f32;
            for cuboid in variant_data(cuboids, canvas) { draw_cuboid(canvas, &scaled(cuboid, scale, true, visual.gas), &visual); }
        }
    }
    if let Some(items) = render_data::render_items(render.block) {
        for (place, stack) in variant_data(items, canvas).iter().zip(render.items.iter()) {
            if let Some(stack) = stack { draw_item(canvas, stack, place); }
        }
    }
    canvas.pop();
}

/// TankBlockEntityRenderer: a seared or scorched tank's fluid, scaled by what it holds of its capacity. The tank
/// is the block entity's own saved `tank`, read by the domain's own reader.
fn render_tank(render: &mut BlockEntityRender<'_>) {
    let path = render.block.rsplit(':').next().unwrap_or(render.block);
    let Some(capacity) = crate::tank::capacity_of(path) else { return };
    let tank = crate::tank::Tank::read(render.data, capacity);
    let Some(held) = &tank.fluid else { return };
    let Some(visual) = visual(&held.fluid) else { return };
    let canvas = &mut *render.canvas;
    // the lanterns have no `block_fluids` data: their fluid is the model's own (LANTERN_FLUID), hanging or standing
    let cuboids: &[Cuboid] = match render_data::fluid_cuboids(render.block) {
        Some(variants) => variant_data(variants, canvas),
        None if crate::lantern::LANTERNS.contains(&path) => {
            if canvas.state_property("hanging").as_deref() == Some("true") { &LANTERN_FLUID_HANGING } else { &LANTERN_FLUID }
        }
        None => return,
    };
    let scale = held.amount as f32 / capacity as f32;
    for cuboid in cuboids { draw_cuboid(canvas, &scaled(cuboid, scale, true, visual.gas), &visual); }
}

/// GaugeBlockEntityRenderer: the fluid of the tank behind the gauge, in the gauge's own fluid cuboids,
/// filled to the mirrored amount of the mirrored capacity. The mirror is the gauge ticker's work
/// (`gauge::set_mirror`); the original's renderer reads the neighbour's tank through the block entity's
/// cached handler instead, which a renderer here cannot do (it sees only its own block entity).
fn render_gauge(render: &mut BlockEntityRender<'_>) {
    let capacity = render.data.get_int("capacity", 0) as i32;
    if capacity <= 0 { return; }
    let tank = crate::tank::Tank::read(render.data, capacity);
    let Some(held) = &tank.fluid else { return };
    let Some(visual) = visual(&held.fluid) else { return };
    let Some(cuboids) = render_data::fluid_cuboids(render.block) else { return };
    let canvas = &mut *render.canvas;
    let scale = held.amount as f32 / capacity as f32;
    for cuboid in variant_data(cuboids, canvas) { draw_cuboid(canvas, &scaled(cuboid, scale, true, visual.gas), &visual); }
}

/// The lanterns' model fluid (the `fluid` of the original's `models/block/template/lantern.json`, and of
/// `lantern_hanging.json` one step higher): the box inside the lantern's glass, on its five outer faces. The
/// original draws it in the model in ten steps of the fill; it is scaled continuously here, as the tanks' are.
const LANTERN_FLUID: [Cuboid; 1] = [Cuboid { from: [5.05, 1.0, 5.05], to: [10.95, 6.0, 10.95], faces: &[Face { dir: "up", flowing: false, rotation: 0 }, Face { dir: "north", flowing: false, rotation: 0 }, Face { dir: "south", flowing: false, rotation: 0 }, Face { dir: "west", flowing: false, rotation: 0 }, Face { dir: "east", flowing: false, rotation: 0 }] }];
const LANTERN_FLUID_HANGING: [Cuboid; 1] = [Cuboid { from: [5.05, 2.0, 5.05], to: [10.95, 7.0, 10.95], faces: &[Face { dir: "up", flowing: false, rotation: 0 }, Face { dir: "north", flowing: false, rotation: 0 }, Face { dir: "south", flowing: false, rotation: 0 }, Face { dir: "west", flowing: false, rotation: 0 }, Face { dir: "east", flowing: false, rotation: 0 }] }];

/// The fluid plates of the io blocks' model (`models/block/template/io_fluid`): a thin plate just outside
/// every face but the back (north as authored, against the smeltery), each showing the model's `fluid`
/// texture. The block's own model draws them with the placeholder black texture; the renderer draws the
/// real fluid over them, as the original's fluid texture loader does with the display fluid.
const IO_PLATES: [Cuboid; 5] = [
    Cuboid { from: [-0.9, 4.0, 4.0], to: [0.0, 12.0, 12.0], faces: &[Face { dir: "west", flowing: false, rotation: 0 }] },
    Cuboid { from: [16.0, 4.0, 4.0], to: [16.9, 12.0, 12.0], faces: &[Face { dir: "east", flowing: false, rotation: 0 }] },
    Cuboid { from: [4.0, 4.0, 16.0], to: [12.0, 12.0, 16.9], faces: &[Face { dir: "south", flowing: false, rotation: 0 }] },
    Cuboid { from: [4.0, 16.0, 4.0], to: [12.0, 16.9, 12.0], faces: &[Face { dir: "up", flowing: false, rotation: 0 }] },
    Cuboid { from: [4.0, -0.9, 4.0], to: [12.0, 0.0, 12.0], faces: &[Face { dir: "down", flowing: false, rotation: 0 }] },
];

/// Draws the io plates in `visual`, turned to the block's facing. The plate is the whole window: the
/// original's model fluid is not scaled by the amount.
fn draw_io_fluid(canvas: &mut dyn BlockEntityCanvas, visual: &Visual) {
    let facing = canvas.state_property("facing").unwrap_or_else(|| "north".to_owned());
    canvas.push();
    rotate_to_facing(canvas, &facing);
    for plate in &IO_PLATES { draw_cuboid(canvas, plate, visual); }
    canvas.pop();
}

/// The drain's display: the fluid its master's tank shows first, mirrored into its data by its ticker
/// (`smeltery_io::display_of`).
fn render_drain(render: &mut BlockEntityRender<'_>) {
    let Some(held) = crate::smeltery_io::display_of(render.data) else { return };
    let Some(visual) = visual(&held.fluid) else { return };
    draw_io_fluid(&mut *render.canvas, &visual);
}

/// The duct's display: the fluid of the container in its slot (`DuctBlockEntity`'s model data), read from
/// the synced items like the original's slot synchronisation keeps the model updated.
fn render_duct(render: &mut BlockEntityRender<'_>) {
    let Some(held) = render.items.first().and_then(Option::as_ref).and_then(crate::smeltery_io::container_fluid) else { return };
    let Some(visual) = visual(&held.fluid) else { return };
    draw_io_fluid(&mut *render.canvas, &visual);
}

/// CastingBlockEntityRenderer: the fluid on the table or in the basin and the items on it, turned to the block's
/// facing. A tank the recipe has filled is drawn whole (the original fades it out over the last 10% of cooling —
/// no alpha here, so it is drawn solid, as is the recipe's output fading in: the output slot's item, or, while
/// cooling with the slot still empty, what the recipe will make).
fn render_casting(render: &mut BlockEntityRender<'_>) {
    let Some((station, _)) = crate::casting::block_rules(render.block) else { return };
    let fluid = host_tank(render.data, 0);
    let state = crate::casting::State::load(render.data, fluid.clone());
    let canvas = &mut *render.canvas;
    let facing = canvas.state_property("facing").unwrap_or_else(|| "north".to_owned());
    canvas.push();
    rotate_to_facing(canvas, &facing);
    if let Some(fluid) = &fluid {
        if let (Some(cuboids), Some(visual)) = (render_data::fluid_cuboids(render.block), visual(&fluid.fluid)) {
            let full = state.capacity > 0 && fluid.amount as i32 == state.capacity;
            for cuboid in variant_data(cuboids, canvas) {
                if full {
                    draw_cuboid(canvas, cuboid, &visual);
                } else {
                    let capacity = state.capacity.max(fluid.amount as i32).max(1);
                    draw_cuboid(canvas, &scaled(cuboid, fluid.amount as f32 / capacity as f32, false, visual.gas), &visual);
                }
            }
        }
    }
    if let Some(places) = render_data::render_items(render.block) {
        let places = variant_data(places, canvas);
        if let (Some(place), Some(Some(stack))) = (places.first(), render.items.first()) { draw_item(canvas, stack, place); }
        if places.len() >= 2 {
            let output = match render.items.get(1) {
                Some(Some(stack)) => Some(stack.clone()),
                _ => match (&state.recipe, &fluid) {
                    (Some(recipe), Some(fluid)) if state.timer > 0 => {
                        crate::casting::recipe_output(station, recipe, render.items.first().and_then(|slot| slot.as_ref()), fluid)
                    }
                    _ => None,
                },
            };
            if let Some(stack) = &output { draw_item(canvas, stack, &places[1]); }
        }
    }
    canvas.pop();
}

/// FaucetBlockEntityRenderer: while pouring, the render fluid in the faucet's own cuboids, turned to its facing
/// (the `facing=down` variant when it hangs), and the stream into the blocks below, which the client tick measured
/// (see `draw_faucet_stream`).
fn render_faucet(render: &mut BlockEntityRender<'_>) {
    let state = crate::faucet::State::load(render.data);
    if !state.is_pouring() { return; }
    let Some(fluid) = &state.render else { return };
    let Some(visual) = visual(&fluid.fluid) else { return };
    let Some(cuboids) = render_data::fluid_cuboids(render.block) else { return };
    let canvas = &mut *render.canvas;
    let facing = canvas.state_property("facing").unwrap_or_else(|| "north".to_owned());
    canvas.push();
    if facing != "down" { rotate_to_facing(canvas, &facing); }
    for cuboid in variant_data(cuboids, canvas) { draw_cuboid(canvas, cuboid, &visual); }
    draw_faucet_stream(canvas, &facing, &visual);
    canvas.pop();
}

/// The stream below a pouring faucet (Mantle's `RenderingHelper.renderFaucetFluids`): the blocks the client tick
/// measured below the faucet, each drawn with its own `faucet_fluid` cuboids — the side form for a side-facing faucet,
/// the center form when it hangs — translated down by its depth, in the faucet's turned frame, as the original draws
/// the stream inside the faucet's rotation. A block with no cuboids for the facing draws nothing, as the original
/// skips it; without client data (an unsupported canvas) there is no stream to draw.
fn draw_faucet_stream(canvas: &mut dyn BlockEntityCanvas, facing: &str, visual: &Visual) {
    // The stream is copied out of the client data: the canvas is drawn to while it is read.
    let Some(stream) = canvas.client_data().and_then(|data| data.get("stream")).and_then(|stream| stream.as_list()).map(|stream| stream.to_vec())
    else {
        return;
    };
    let center = facing == "down" || facing == "up";
    for (index, entry) in stream.iter().enumerate() {
        let Some(text) = entry.as_str() else { continue };
        let Ok(state) = BlockState::parse(text) else { continue };
        let fluid = render_data::faucet_fluid(&state);
        let cuboids = if center { fluid.center } else { fluid.side };
        if cuboids.is_empty() { continue; }
        canvas.push();
        canvas.translate([0.0, -(index as f32 + 1.0), 0.0]);
        for cuboid in cuboids { draw_cuboid(canvas, cuboid, visual); }
        canvas.pop();
    }
}

/// Which side of a channel the center flows toward (ChannelBlockEntityRenderer): nowhere (up) while no out side
/// flows, that side while exactly one does, and down — the fail state — when two disagree.
pub(crate) fn center_flow(flowing_out: &[Direction]) -> Option<Direction> {
    match flowing_out { [] => None, [only] => Some(*only), _ => None }
}

/// ChannelBlockEntityRenderer: each connected side's cuboid (the flow form while the side flows — in or out —
/// the still form otherwise, with the edge against the neighbour), the center in its still or flowing form, and
/// the drop below the center while the down side flows. The stream below that is `renderFaucetFluids` (not drawn,
/// see the module docs), and the edge is drawn without the original's neighbour check, which a renderer cannot
/// make.
fn render_channel(render: &mut BlockEntityRender<'_>) {
    let Some(fluid) = host_tank(render.data, 0) else { return };
    let Some(visual) = visual(&fluid.fluid) else { return };
    let state = crate::channel::State::load(render.data, Some(fluid));
    let canvas = &mut *render.canvas;
    let model = &render_data::CHANNEL_FLUIDS;
    let mut flowing_out = Vec::new();
    for side in [Direction::North, Direction::East, Direction::South, Direction::West] {
        let connection = crate::channel::Connection::parse(canvas.state_property(side.name()).as_deref());
        if !connection.can_flow() { continue; }
        canvas.push();
        rotate_to_side(canvas, side);
        if state.is_flowing(side) {
            draw_cuboid(canvas, if connection == crate::channel::Connection::Out { &model.side_out } else { &model.side_in }, &visual);
            draw_cuboid(canvas, &model.side_edge, &visual);
            if connection == crate::channel::Connection::Out { flowing_out.push(side); }
        } else {
            draw_cuboid(canvas, &model.side_still, &visual);
        }
        canvas.pop();
    }
    match center_flow(&flowing_out) {
        Some(flow) => {
            canvas.push();
            rotate_to_side(canvas, flow);
            draw_cuboid(canvas, &model.center_flowing, &visual);
            canvas.pop();
        }
        None => draw_cuboid(canvas, &model.center_still, &visual),
    }
    if canvas.state_property("down").as_deref() == Some("true") && state.is_flowing(Direction::Down) {
        draw_cuboid(canvas, &model.down, &visual);
    }
}

/// `GuiSmelteryTank.calcLiquidHeights`: each fluid's height in `height` units for its share of `capacity`, at
/// least `min`, with `min` left over for the empty part of the tank while it is not full, and the excess taken
/// from the tallest fluids one unit at a time.
pub(crate) fn calc_liquid_heights(amounts: &[i32], capacity: i32, height: i32, min: i32) -> Vec<i32> {
    let mut heights = vec![0; amounts.len()];
    if amounts.is_empty() || capacity <= 0 { return heights; }
    let mut total = 0;
    for (index, amount) in amounts.iter().enumerate() {
        total += amount;
        heights[index] = min.max((*amount as f32 / capacity as f32 * height as f32).ceil() as i32);
    }
    let mut height = height;
    if total < capacity { height -= min; }
    loop {
        let mut sum = 0;
        let mut biggest = -1;
        let mut m = 0;
        for (index, held) in heights.iter().enumerate() {
            sum += held;
            if *held > biggest { biggest = *held; m = index; }
        }
        if heights[m] == 0 || sum <= height { break; }
        heights[m] -= 1;
    }
    heights
}

/// The position saved in a structure tag (`{X, Y, Z}`), relative to the controller.
fn saved_pos(tag: &NbtCompound) -> [i32; 3] { [tag.get_int("X", 0) as i32, tag.get_int("Y", 0) as i32, tag.get_int("Z", 0) as i32] }

/// HeatingStructureBlockEntityRenderer: the controller tank's fluids layered over the structure's inside and the
/// melting inventory's items floating in it, in slot order (a layer of the inside's floor plan per height). The
/// structure's bounds are its saved outer bounds; the inside is one block in from the walls and the floor, with
/// no ceiling (both multiblocks of `crate::multiblock` are floored and ceilingless). The error-block highlight is
/// not drawn (see the module docs).
fn render_controller(render: &mut BlockEntityRender<'_>) {
    let canvas = &mut *render.canvas;
    if canvas.state_property("in_structure").as_deref() != Some("true") { return; }
    let Some(structure) = render.data.get_compound("multiblock") else { return };
    let (Some(min_tag), Some(max_tag)) = (structure.get_compound("min"), structure.get_compound("max")) else { return };
    let (min, max) = (saved_pos(min_tag), saved_pos(max_tag));
    let min_in = [min[0] + 1, min[1] + 1, min[2] + 1];
    let max_in = [max[0] - 1, max[1], max[2] - 1];
    let (xd, yd, zd) = (max_in[0] - min_in[0], max_in[1] - min_in[1] + 1, max_in[2] - min_in[2]);
    if xd < 0 || zd < 0 || yd <= 0 { return; }
    let mut tank = crate::smeltery_tank::SmelteryTank::default();
    if let Some(tag) = render.data.get_compound("tank") { tank.read(tag); }
    // the controller's own window (`models/block/template/controller_fluid`): the tank's first fluid, the
    // block entity's display fluid, on the plate proud of the front face — the unformed model has no window,
    // which the in-structure check above already answers for
    if let Some(first) = tank.fluids().first() {
        if let Some(visual) = visual(&first.fluid) {
            let facing = canvas.state_property("facing").unwrap_or_else(|| "north".to_owned());
            canvas.push();
            rotate_to_facing(canvas, &facing);
            draw_cuboid(canvas, &CONTROLLER_WINDOW, &visual);
            canvas.pop();
        }
    }
    canvas.push();
    canvas.translate([min_in[0] as f32, min_in[1] as f32, min_in[2] as f32]);
    // SmelteryTankRenderer.renderFluids: layers in tank order from the floor, 1000 units to a block of height
    if tank.capacity() > 0 && !tank.fluids().is_empty() {
        let amounts: Vec<i32> = tank.fluids().iter().map(|fluid| fluid.amount).collect();
        let heights = calc_liquid_heights(&amounts, tank.capacity(), yd * 1000 - 10, 100);
        let mut y = 0.005f32;
        for (held, height) in tank.fluids().iter().zip(heights) {
            let height = height as f32 / 1000.0;
            if height > 0.0 {
                if let Some(visual) = visual(&held.fluid) {
                    let layer = Cuboid {
                        from: [0.08, y * 16.0, 0.08],
                        to: [(xd as f32 + 0.995) * 16.0, (y + height) * 16.0, (zd as f32 + 0.995) * 16.0],
                        faces: &ALL_FACES,
                    };
                    draw_cuboid(canvas, &layer, &visual);
                }
            }
            y += height;
        }
    }
    // the melting items: slot order fills a layer of the inside's floor plan, then the next height
    let layer = ((xd + 1) * (zd + 1)) as usize;
    if layer > 0 {
        let slots = render.data.get_compound("inventory").map_or(usize::MAX, |inventory| inventory.get_int("size", 0) as usize);
        let facing = canvas.state_property("facing").unwrap_or_else(|| "north".to_owned());
        for (index, stack) in render.items.iter().enumerate().take(slots) {
            let Some(stack) = stack else { continue };
            let (height, within) = ((index / layer) as f32, index % layer);
            let (ox, oz) = ((within % (xd + 1) as usize) as f32, (within / (xd + 1) as usize) as f32);
            canvas.push();
            canvas.translate([ox + 0.5, height + 0.5, oz + 0.5]);
            let degrees = facing_degrees(&facing);
            if degrees != 0.0 { canvas.rotate_about([0.0, 1.0, 0.0], degrees, [0.0; 3]); }
            canvas.scale([15.0 / 16.0; 3]);
            canvas.item_with_context(stack, ItemDisplayContext::None);
            canvas.pop();
        }
    }
    canvas.pop();
}

/// The fluid window of a heating controller's model (`models/block/template/controller_fluid`): the plate
/// proud of the front face (north as authored), showing the display fluid.
const CONTROLLER_WINDOW: Cuboid = Cuboid { from: [3.0, 10.0, -1.0], to: [13.0, 15.0, 0.0], faces: &[Face { dir: "north", flowing: false, rotation: 0 }] };

/// Every face of a cuboid, for boxes the renderers build themselves (the smeltery's fluid layers).
const ALL_FACES: [Face; 6] = [
    Face { dir: "down", flowing: false, rotation: 0 }, Face { dir: "up", flowing: false, rotation: 0 },
    Face { dir: "north", flowing: false, rotation: 0 }, Face { dir: "south", flowing: false, rotation: 0 },
    Face { dir: "west", flowing: false, rotation: 0 }, Face { dir: "east", flowing: false, rotation: 0 },
];

/// Registers every renderer of this unit (the blocks of `SmelteryClientEvents.registerRenderers` that this port
/// has block entities for; the alloyer, the fluid cannons, the casting tank and the proxy tank have no renderer
/// here yet, so they have nothing to draw).
pub(crate) fn register() {
    let on = |names: &[&str], renderer: fn(&mut BlockEntityRender<'_>)| {
        for name in names {
            BlockEntityRendererRegistry::register(Identifier::new("tconstruct", name).expect("valid renderer block id"), renderer);
        }
    };
    on(&["seared_melter"], render_melter);
    let tanks: Vec<String> = crate::tank::blocks().into_iter().map(|(name, _)| name).collect();
    for name in &tanks {
        BlockEntityRendererRegistry::register(Identifier::new("tconstruct", name).expect("valid tank block id"), render_tank);
    }
    on(&crate::lantern::LANTERNS, render_tank);
    on(&["seared_table", "scorched_table", "seared_basin", "scorched_basin"], render_casting);
    on(&crate::faucet::BLOCKS, render_faucet);
    on(&crate::channel::BLOCKS, render_channel);
    on(&[crate::smeltery_menu::SMELTERY, crate::smeltery_menu::FOUNDRY], render_controller);
    on(&[crate::gauge::RENDERING_GAUGE], render_gauge);
    on(&crate::smeltery_io::DRAINS, render_drain);
    on(&crate::smeltery_io::DUCTS, render_duct);
}

