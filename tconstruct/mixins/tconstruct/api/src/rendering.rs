    #[derive(Default)]
    struct Recorder { log: Vec<String>, props: Vec<(&'static str, &'static str)> }

    fn point(v: [f32; 3]) -> String { format!("[{:.4}, {:.4}, {:.4}]", v[0], v[1], v[2]) }

    impl BlockEntityCanvas for Recorder {
        fn state_property(&self, name: &str) -> Option<String> { self.props.iter().find(|(key, _)| *key == name).map(|(_, value)| value.to_string()) }
        fn push(&mut self) { self.log.push("push".into()); }
        fn pop(&mut self) { self.log.push("pop".into()); }
        fn translate(&mut self, by: [f32; 3]) { self.log.push(format!("translate {}", point(by))); }
        fn rotate_about(&mut self, axis: [f32; 3], degrees: f32, pivot: [f32; 3]) { self.log.push(format!("rotate {} {degrees:.1} {}", point(axis), point(pivot))); }
        fn scale(&mut self, by: [f32; 3]) { self.log.push(format!("scale {}", point(by))); }
        fn quad(&mut self, sprite: &str, corners: [[f32; 3]; 4], uv: [f32; 4], tint: u32) -> bool {
            let corners: Vec<String> = corners.iter().map(|corner| point(*corner)).collect();
            self.log.push(format!("quad {sprite} {} uv [{:.2}, {:.2}, {:.2}, {:.2}] tint {tint:06X}", corners.join(" "), uv[0], uv[1], uv[2], uv[3]));
            true
        }
        fn cube(&mut self, from: [f32; 3], to: [f32; 3], sprite: &str, tint: u32) -> bool {
            self.log.push(format!("cube {sprite} {} -> {} tint {tint:06X}", point(from), point(to)));
            true
        }
        fn block(&mut self, _: &str, _: &[(&str, &str)]) -> bool { false }
        fn item(&mut self, _: &ItemSlot) -> bool { false }
        fn item_with_context(&mut self, item: &ItemSlot, context: ItemDisplayContext) -> bool {
            self.log.push(format!("item {} x{} {context:?}", item.item, item.count));
            true
        }
        fn model(&mut self, _: &str, _: u32) -> bool { false }
        fn keep(&mut self) {}
    }

    fn id(text: &str) -> Identifier { Identifier::parse(text).unwrap() }
    fn stack(text: &str) -> ItemSlot { ItemSlot::new(id(text), 1) }

    fn host_fluid(fluid: &str, amount: i32) -> NbtCompound {
        let mut tank = NbtCompound::new();
        tank.insert("Fluid".into(), Nbt::String(fluid.into()));
        tank.insert("Amount".into(), Nbt::Int(amount));
        let mut data = NbtCompound::new();
        data.insert("fluids".into(), Nbt::List(vec![Nbt::Compound(tank)]));
        data
    }

    fn run(block: &'static str, data: &NbtCompound, items: &[Option<ItemSlot>], props: Vec<(&'static str, &'static str)>) -> Vec<String> {
        crate::fluids::register();
        let mut recorder = Recorder { props, ..Recorder::default() };
        {
            let mut render = BlockEntityRender { pos: [0, 64, 0], block, data, items, canvas: &mut recorder };
            match block {
                "tconstruct:seared_melter" => render_melter(&mut render),
                "tconstruct:seared_ingot_tank" | "tconstruct:seared_fuel_tank" => render_tank(&mut render),
                "tconstruct:seared_table" => render_casting(&mut render),
                "tconstruct:seared_faucet" => render_faucet(&mut render),
                "tconstruct:seared_channel" => render_channel(&mut render),
                "tconstruct:smeltery_controller" => render_controller(&mut render),
                _ => panic!("no test renderer for {block}"),
            }
        }
        recorder.log
    }

