// Minecraft 1.20.1 SimpleJsonResourceReloadListener uses a Java HashMap for
// successfully parsed JSON recipes. RecipeManager retains that iteration
// order for each type. Not connected to gameplay yet.

#[derive(Debug, PartialEq, Eq)]
pub(super) enum OrderError { InvalidId, TreeBin }

fn string_hash(s: &str) -> u32 {
    s.encode_utf16().fold(0u32, |hash, c| hash.wrapping_mul(31).wrapping_add(u32::from(c)))
}
fn components(id: &str) -> Result<(&str, &str), OrderError> {
    let (namespace, path) = id.split_once(':').ok_or(OrderError::InvalidId)?;
    if namespace.is_empty() || path.is_empty() { return Err(OrderError::InvalidId); }
    Ok((namespace, path))
}
fn hash(id: &str) -> Result<u32, OrderError> {
    let (namespace, path) = components(id)?;
    let value = string_hash(namespace).wrapping_mul(31).wrapping_add(string_hash(path));
    Ok(value ^ (value >> 16))
}
fn resize(buckets: &mut Vec<Vec<(u32, String)>>) {
    let old_capacity = buckets.len();
    let mut next = vec![Vec::new(); old_capacity * 2];
    for (index, bucket) in std::mem::take(buckets).into_iter().enumerate() {
        for entry in bucket {
            let target = if entry.0 & old_capacity as u32 == 0 { index } else { index + old_capacity };
            next[target].push(entry);
        }
    }
    *buckets = next;
}

/// Input must contain *all* successfully parsed recipe IDs, including Forge
/// `_` metadata. Missing vanilla/Forge/mod files would change table capacity
/// and therefore the result. Tree bins are deliberately rejected until their
/// exact Java insertion/iteration semantics have been implemented.
#[allow(dead_code)]
pub(super) fn java_recipe_order(ids: &[String]) -> Result<Vec<String>, OrderError> {
    let mut ordered = Vec::with_capacity(ids.len());
    for id in ids { let (namespace, path) = components(id)?; ordered.push((path.to_owned(), namespace.to_owned(), id.clone())); }
    ordered.sort();
    ordered.dedup_by(|a, b| a.2 == b.2);
    let mut buckets = vec![Vec::<(u32, String)>::new(); 16];
    let mut size = 0usize;
    for (_, _, id) in ordered {
        let h = hash(&id)?;
        let slot = h as usize & (buckets.len() - 1);
        let treeify = buckets[slot].len() >= 8;
        buckets[slot].push((h, id));
        size += 1;
        if treeify {
            if buckets.len() >= 64 { return Err(OrderError::TreeBin); }
            resize(&mut buckets);
        }
        if size > buckets.len() * 3 / 4 { resize(&mut buckets); }
    }
    Ok(buckets.into_iter().flatten().map(|(_, id)| id).collect())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn rejects_java_tree_bins_instead_of_claiming_an_order() {
        // The Java string hashes of "an" and "c0" are equal; concatenating
        // either four times creates sixteen distinct colliding resource IDs.
        let ids = (0..16).map(|bits| {
            let mut path = String::new();
            for n in 0..4 { path.push_str(if bits & (1 << n) == 0 { "an" } else { "c0" }); }
            format!("test:{path}")
        }).collect::<Vec<_>>();
        assert_eq!(java_recipe_order(&ids), Err(OrderError::TreeBin));
    }
    #[test]
    fn matches_java_hashmap_after_resize() {
        let ids = "minecraft:stone tconstruct:flint tconstruct:wood forge:iron minecraft:stick x:alpha a:zeta a:beta z:alpha foo:bar a:_metadata minecraft:planks x:c tconstruct:a z:zz minecraft:gold x:d b:bar c:bar e:e f:f g:g h:h i:i j:j k:k l:l m:m n:n o:o p:p q:q".split_whitespace().map(str::to_owned).collect::<Vec<_>>();
        // Generated by Java 25 HashMap using Minecraft 1.20.1's ResourceLocation
        // hash and TreeMap comparator (path, then namespace).
        let expected = "f:f h:h j:j l:l n:n p:p a:beta minecraft:stone z:zz tconstruct:flint minecraft:planks tconstruct:a forge:iron c:bar minecraft:gold a:_metadata minecraft:stick e:e g:g i:i k:k m:m o:o q:q tconstruct:wood x:c x:d z:alpha a:zeta x:alpha b:bar foo:bar".split_whitespace().map(str::to_owned).collect::<Vec<_>>();
        assert_eq!(java_recipe_order(&ids).unwrap(), expected);
    }
}
