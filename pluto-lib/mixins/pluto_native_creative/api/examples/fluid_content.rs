//! Generate shared block content plus a consumer-owned registration helper.
//! Usage: fluid_content DEFINITION.json CONTENT_DIRECTORY REGISTRATION.rs
use pluto_api::fluid::{content, Definition};
use std::{env, fs, path::PathBuf};
fn main() -> Result<(), Box<dyn std::error::Error>> {
    let args: Vec<_> = env::args_os().skip(1).collect();
    if args.len() != 3 {
        return Err("expected definition, content directory and registration helper paths".into());
    }
    let text = fs::read_to_string(&args[0])?;
    let definition = Definition::from_json(&text)?;
    let root = PathBuf::from(&args[1]);
    for (relative, value) in content(&definition)? {
        let file = root.join(relative);
        fs::create_dir_all(file.parent().unwrap())?;
        fs::write(file, serde_json::to_string_pretty(&value)? + "\n")?;
    }
    let literal = serde_json::to_string(&text)?;
    let source = format!("// Generated by PlutoLib fluid_content from the consumer definition.\nfn register_world_fluid() {{\n    let definition = pluto_api::fluid::Definition::from_json({literal}).expect(\"valid generated fluid definition\");\n    pluto_api::fluid::register(definition).expect(\"unique world fluid identity\");\n}}\n");
    fs::write(&args[2], source)?;
    Ok(())
}
